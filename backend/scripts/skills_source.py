def build() -> list[dict[str, object]]:
    """Aliases prefixed with "~" are too ambiguous to detect in free text ("the rest of",
    "send your CV") but are still accepted when a student types them in their profile."""
    return [
        {
            "name": name,
            "aliases": [a for a in aliases if not a.startswith("~")],
            "normalise_only": [a[1:] for a in aliases if a.startswith("~")],
            "strict": flags == S,
        }
        for name, aliases, flags in SKILLS
    ]


if __name__ == "__main__":
    out = Path(__file__).resolve().parents[1] / "data" / "skills.json"
    data = build()
    out.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {len(data)} skills to {out}")
